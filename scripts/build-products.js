/*
 * build-products.js
 * One-time helper: pulls sample products from DummyJSON (https://dummyjson.com),
 * maps them to this project's 6 categories, downloads the images locally and
 * writes js/products-data.js.
 *
 * Run from the project root:   node scripts/build-products.js
 * Needs Node 18+ (built-in fetch) and an internet connection.
 */

const fs = require("fs");
const path = require("path");

const PROJECT_ROOT = process.argv[2]
    ? path.resolve(process.argv[2])
    : path.join(__dirname, "..");

const IMAGES_DIR = path.join(PROJECT_ROOT, "images", "products");
const OUTPUT_FILE = path.join(PROJECT_ROOT, "js", "products-data.js");

// How the HTML pages (inside /html) reach the images. Change it here only.
const IMAGE_BASE = "../images/products/";
const FALLBACK_IMAGE = "../images/placeholder.svg";

// our category value -> DummyJSON categories to draw from, and how many to keep
const PLAN = {
    electronics: { count: 7, from: ["smartphones", "laptops", "tablets", "mobile-accessories"] },
    fashion:     { count: 7, from: ["mens-shirts", "womens-dresses", "mens-shoes", "tops", "womens-shoes"] },
    home:        { count: 6, from: ["furniture", "home-decoration", "kitchen-accessories"] },
    beauty:      { count: 6, from: ["beauty", "skin-care", "fragrances"] },
    sports:      { count: 5, from: ["sports-accessories"] },
    accessories: { count: 7, from: ["sunglasses", "womens-bags", "womens-watches", "mens-watches", "womens-jewellery"] },
};

async function getJson(url) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
    return res.json();
}

// take items from several lists in turn, so one source category doesn't dominate
function interleave(lists, limit) {
    const out = [];
    let i = 0;
    while (out.length < limit && lists.some((l) => i < l.length)) {
        for (const l of lists) {
            if (i < l.length && out.length < limit) out.push(l[i]);
        }
        i++;
    }
    return out;
}

async function downloadImage(url, fileBase) {
    try {
        const ext = path.extname(new URL(url).pathname) || ".webp";
        const fileName = fileBase + ext;
        const res = await fetch(url);
        if (!res.ok) throw new Error(String(res.status));
        fs.writeFileSync(path.join(IMAGES_DIR, fileName), Buffer.from(await res.arrayBuffer()));
        return IMAGE_BASE + fileName;
    } catch (err) {
        console.warn(`  image failed (${url}): ${err.message}`);
        return FALLBACK_IMAGE;
    }
}

async function main() {
    fs.mkdirSync(IMAGES_DIR, { recursive: true });
    fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });

    const products = [];
    let id = 1;

    for (const [category, { count, from }] of Object.entries(PLAN)) {
        console.log(`Category: ${category}`);
        const lists = [];
        for (const slug of from) {
            const data = await getJson(`https://dummyjson.com/products/category/${slug}?limit=0`);
            lists.push(data.products);
        }

        for (const p of interleave(lists, count)) {
            const num = String(id).padStart(2, "0");
            const imageUrl = (p.images && p.images[0]) || p.thumbnail;
            const image = await downloadImage(imageUrl, "p" + num);
            console.log(`  p${num}  ${p.title}`);

            products.push({
                id: id,
                name: p.title,
                description: p.description,
                category: category,
                price: p.price,
                rating: Math.round(p.rating * 10) / 10,
                reviewCount: (p.reviews || []).length,
                stock: p.stock,
                image: image,
                createdAt: (p.meta && p.meta.createdAt) || null,
                // reviewer emails are dropped on purpose
                reviews: (p.reviews || []).map((r) => ({
                    rating: r.rating,
                    comment: r.comment,
                    author: r.reviewerName,
                    date: r.date,
                })),
            });
            id++;
        }
    }

    const header =
        "// Sample product data generated by scripts/build-products.js\n" +
        "// Source: DummyJSON (dummyjson.com). Sample data for the course demo.\n\n";
    fs.writeFileSync(OUTPUT_FILE, header + "const products = " + JSON.stringify(products, null, 2) + ";\n");

    console.log(`\nDone: ${products.length} products -> ${path.relative(PROJECT_ROOT, OUTPUT_FILE)}`);
}

main().catch((err) => {
    console.error("Failed:", err.message);
    process.exit(1);
});